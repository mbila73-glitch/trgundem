function escapeMd(s) {
  if (!s)
    return "";
  return s.replace(/\[/g, "\\[").replace(/\]/g, "\\]").replace(/\r?\n/g, " ").trim();
}
function fmtDate(d) {
  if (!d)
    return "";
  const date = typeof d === "string" ? new Date(d) : d;
  if (Number.isNaN(date.getTime()))
    return "";
  return format(date, "d MMM yyyy HH:mm", { locale: tr });
}
